-- Runtime asset delivery metadata for S3/CloudFront-hosted Unity assets.

ALTER TABLE assets
    ADD COLUMN IF NOT EXISTS collection_code varchar(80),
    ADD COLUMN IF NOT EXISTS content_type varchar(120),
    ADD COLUMN IF NOT EXISTS file_size bigint,
    ADD COLUMN IF NOT EXISTS file_hash varchar(160),
    ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1;

CREATE INDEX IF NOT EXISTS idx_assets_collection_code
    ON assets(collection_code);

CREATE INDEX IF NOT EXISTS idx_assets_type_collection_active
    ON assets(asset_type, collection_code, is_active);

CREATE TABLE IF NOT EXISTS theme_asset_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    theme_asset_id bigint NOT NULL,
    child_asset_id bigint NOT NULL,
    role varchar(80) NOT NULL,
    is_required boolean NOT NULL DEFAULT true,
    transform_json text,
    sort_order integer NOT NULL DEFAULT 0,
    CONSTRAINT fk_theme_asset_items_theme_asset_id FOREIGN KEY (theme_asset_id) REFERENCES assets(id),
    CONSTRAINT fk_theme_asset_items_child_asset_id FOREIGN KEY (child_asset_id) REFERENCES assets(id),
    CONSTRAINT uk_theme_asset_items_theme_child_role UNIQUE (theme_asset_id, child_asset_id, role)
);

CREATE INDEX IF NOT EXISTS idx_theme_asset_items_theme
    ON theme_asset_items(theme_asset_id, sort_order, id);

CREATE INDEX IF NOT EXISTS idx_theme_asset_items_child
    ON theme_asset_items(child_asset_id);
