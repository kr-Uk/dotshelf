CREATE TABLE public.payment_orders (
    id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    user_id bigint NOT NULL,
    order_id character varying(40) NOT NULL,
    provider_transaction_id character varying(40),
    provider character varying(20) NOT NULL,
    status character varying(30) NOT NULL,
    order_name character varying(100) NOT NULL,
    pages_amount integer NOT NULL,
    amount_krw integer NOT NULL,
    currency character varying(3) NOT NULL,
    buyer_name character varying(30),
    buyer_tel character varying(20),
    buyer_email character varying(60),
    auth_token character varying(500),
    auth_url character varying(500),
    net_cancel_url character varying(500),
    idc_name character varying(20),
    pay_method character varying(50),
    requested_at timestamp(6) without time zone NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    authenticated_at timestamp(6) without time zone,
    approved_at timestamp(6) without time zone,
    failed_at timestamp(6) without time zone,
    canceled_at timestamp(6) without time zone,
    failure_code character varying(100),
    failure_message character varying(500)
);

ALTER TABLE public.payment_orders ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.payment_orders_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.payment_orders
    ADD CONSTRAINT payment_orders_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.payment_orders
    ADD CONSTRAINT payment_orders_order_id_key UNIQUE (order_id);

ALTER TABLE ONLY public.payment_orders
    ADD CONSTRAINT payment_orders_provider_transaction_id_key UNIQUE (provider_transaction_id);

CREATE INDEX idx_payment_orders_user_id_created_at
    ON public.payment_orders USING btree (user_id, created_at DESC);

