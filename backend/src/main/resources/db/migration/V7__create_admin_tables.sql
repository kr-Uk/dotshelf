CREATE TABLE IF NOT EXISTS admin.admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    actor_user_id BIGINT NOT NULL,
    action VARCHAR(80) NOT NULL,
    target_type VARCHAR(80) NOT NULL,
    target_id BIGINT,
    before_payload TEXT,
    after_payload TEXT,
    reason VARCHAR(500),
    ip_address VARCHAR(45)
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_actor_user_id
    ON admin.admin_audit_logs(actor_user_id);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_action
    ON admin.admin_audit_logs(action);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_target
    ON admin.admin_audit_logs(target_type, target_id);
CREATE INDEX IF NOT EXISTS idx_admin_audit_logs_created_at
    ON admin.admin_audit_logs(created_at DESC);

CREATE TABLE IF NOT EXISTS admin.admin_user_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    author_user_id BIGINT NOT NULL,
    body VARCHAR(1000) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_user_notes_user_id
    ON admin.admin_user_notes(user_id);

CREATE TABLE IF NOT EXISTS admin.admin_announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    title VARCHAR(150) NOT NULL,
    body TEXT NOT NULL,
    audience VARCHAR(30) NOT NULL,
    starts_at TIMESTAMP(6) WITHOUT TIME ZONE,
    ends_at TIMESTAMP(6) WITHOUT TIME ZONE,
    is_urgent BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_user_id BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_announcements_created_at
    ON admin.admin_announcements(created_at DESC);

CREATE TABLE IF NOT EXISTS admin.policy_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    policy_type VARCHAR(50) NOT NULL,
    version VARCHAR(30) NOT NULL,
    title VARCHAR(150) NOT NULL,
    body TEXT,
    effective_at TIMESTAMP(6) WITHOUT TIME ZONE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    published_by_user_id BIGINT
);

CREATE INDEX IF NOT EXISTS idx_policy_versions_policy_type
    ON admin.policy_versions(policy_type);

CREATE TABLE IF NOT EXISTS admin.maintenance_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    message VARCHAR(500),
    updated_by_user_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS admin.creator_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE IF NOT EXISTS admin.settlement_withdrawals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    creator_user_id BIGINT NOT NULL,
    requested_pages INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    requested_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    reviewed_by_user_id BIGINT,
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    memo VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS idx_settlement_withdrawals_creator_user_id
    ON admin.settlement_withdrawals(creator_user_id);
CREATE INDEX IF NOT EXISTS idx_settlement_withdrawals_status
    ON admin.settlement_withdrawals(status);

CREATE TABLE IF NOT EXISTS admin.settlement_payout_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    batch_code VARCHAR(80) NOT NULL UNIQUE,
    total_pages INTEGER NOT NULL DEFAULT 0,
    withdrawal_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'READY',
    scheduled_at TIMESTAMP(6) WITHOUT TIME ZONE,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS admin.settlement_account_change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    bank_name VARCHAR(80) NOT NULL,
    account_number_masked VARCHAR(80) NOT NULL,
    account_holder VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    requested_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    reviewed_by_user_id BIGINT,
    reviewed_at TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_settlement_account_change_requests_user_id
    ON admin.settlement_account_change_requests(user_id);

CREATE TABLE IF NOT EXISTS admin.settlement_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    user_id BIGINT NOT NULL,
    delta_pages INTEGER NOT NULL,
    reason VARCHAR(80) NOT NULL,
    memo VARCHAR(500),
    adjusted_by_user_id BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_settlement_adjustments_user_id
    ON admin.settlement_adjustments(user_id);
